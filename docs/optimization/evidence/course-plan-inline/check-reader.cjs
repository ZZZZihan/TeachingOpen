async page => {
  const checks = [];
  const check = (value, name) => { if (!value) throw new Error(name); checks.push(name); };
  let downloads = 0; let popups = 0;
  const onDownload = () => downloads++; const onPopup = () => popups++;
  page.on('download', onDownload); page.on('popup', onPopup);
  const initialUrl = page.url();
  const dialog = page.getByRole('dialog');
  const open = async name => {
    if (await dialog.count()) await dialog.getByRole('button', {name:'Close',exact:true}).click();
    await page.getByRole('button',{name:'打开单元：' + name,exact:true}).click();
    await dialog.getByRole('button',{name:'课程教案 1',exact:true}).click();
  };
  try {
    await page.setViewportSize({width:1440,height:1000});
    await page.goto(initialUrl);
    await page.waitForLoadState("networkidle");
    await open('MD 教案在线阅读');
    await dialog.getByRole('heading',{name:'合成 Markdown 课程教案',exact:true}).waitFor();
    check(await dialog.locator('table tbody tr').count() === 2,'Markdown table rendered');
    check((await dialog.locator('pre code').innerText()).includes('hello reader'),'Markdown code rendered');
    check(await dialog.locator('.plan-document ul li').count() === 3,'Markdown list rendered');
    check(await page.evaluate(() => window.readerInjected === undefined),'Raw script did not run');
    check(await dialog.locator('.plan-document script').count() === 0,'No script element');
    await page.screenshot({path:'output/playwright/after-1440.png',fullPage:false,animations:"disabled"});
    await page.setViewportSize({width:390,height:844});
    await page.goto(initialUrl);
    await page.waitForLoadState("networkidle");
    await open('MD 教案在线阅读');
    await dialog.getByRole('heading',{name:'合成 Markdown 课程教案',exact:true}).waitFor();
    check(await page.evaluate(() => document.querySelector('.ant-modal').getBoundingClientRect().right <= innerWidth),'Mobile dialog fits viewport');
    check(await dialog.getByRole('heading',{name:'合成 Markdown 课程教案',exact:true}).isVisible(),'Mobile Markdown readable');
    await page.screenshot({path:'output/playwright/after-390.png',fullPage:false,animations:"disabled"});
    await dialog.getByRole('button',{name:'Close',exact:true}).click();
    await page.setViewportSize({width:1440,height:1000});
    await page.goto(initialUrl);
    await page.waitForLoadState("networkidle");
    await page.route('**/reader-plan/lesson.md', route => route.abort('failed'), {times:1});
    await page.getByRole('button',{name:'打开单元：MD 教案在线阅读',exact:true}).click();
    await dialog.getByRole('button',{name:'课程教案 1',exact:true}).click();
    await dialog.getByRole('heading',{name:'教案暂时无法显示',exact:true}).waitFor();
    await page.screenshot({path:'output/playwright/network-error-1440.png',fullPage:false,animations:"disabled"});
    await dialog.getByRole('button',{name:'重新加载教案',exact:true}).click();
    await dialog.getByRole('heading',{name:'合成 Markdown 课程教案',exact:true}).waitFor();
    check(true,'Network fault followed by real retry succeeds');
    await open('TXT 教案在线阅读');
    await dialog.locator('.plan-text').waitFor();
    check((await dialog.locator('.plan-text').innerText()).includes('合成纯文本课程教案'),'Text shown inline');
    check(await dialog.getByRole('heading',{name:'合成 Markdown 课程教案',exact:true}).count() === 0,'Previous unit content cleared');
    await open('PDF 教案在线阅读');
    await dialog.locator('iframe.plan-pdf').waitFor();
    check((await dialog.locator('iframe.plan-pdf').getAttribute('src')).startsWith('blob:'),'PDF displayed using typed memory blob');
    await open('PNG 教案在线阅读');
    await dialog.locator('img.plan-image').waitFor();
    await page.waitForFunction(() => document.querySelector('img.plan-image')?.naturalWidth > 0);
    check(true,'Image decoded inline');
    await open('DOCX 教案在线阅读');
    await dialog.getByText('此格式暂不支持在线阅读，请联系老师将教案转换为 Markdown 或 PDF。',{exact:true}).waitFor();
    check(true,'Word conversion guidance without download');
    await dialog.getByRole('button',{name:'Close',exact:true}).click();
    await page.getByRole('button',{name:'打开单元：隐藏教案（学生不可见）',exact:true}).click();
    check(await dialog.getByRole('button',{name:'课程教案',exact:true}).count() === 0,'Hidden teacher plan not exposed to student');
    await open('文件失效后的重试');
    await dialog.getByText('教案文件不存在，请联系老师更新。',{exact:true}).waitFor();
    check(true,'Real 404 reported');
    await open('MD 教案在线阅读');
    await dialog.getByRole('heading',{name:'合成 Markdown 课程教案',exact:true}).waitFor();
    check(page.url() === initialUrl,'No document navigation');
    check(downloads === 0,'Zero downloads during candidate reader actions');
    check(popups === 0,'Zero popup tabs during candidate reader actions');
    return {candidate:'daeb31a9',checks,downloads,popups,viewports:['1440x1000','390x844'],auth:'real API login imported as private browser state',network:'real local backend; one deliberate request abort for recovery'};
  } finally { page.off('download',onDownload); page.off('popup',onPopup); }
}
